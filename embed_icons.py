"""Embeds the app icons into icon_data.py so FlowGet never depends on an icon folder at run time.

Looks for the first folder named files-logo or assets that contains icon.ico plus icon-16/32/48/256.png,
writes icon_data.py, and prints the folder name (build scripts use it for the exe and installer icon).
"""
import base64, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
FOLDERS = ("files-logo", "assets")
SIZES = (16, 32, 48, 256)


KEEP = {b"IHDR", b"PLTE", b"tRNS", b"IDAT", b"IEND", b"sRGB", b"gAMA"}


def strip_png(data):
    """Drop metadata chunks (EXIF, text, content credentials...) and keep only what draws the image."""
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG file")
    out, i = [data[:8]], 8
    while i < len(data):
        n = struct.unpack(">I", data[i:i + 4])[0]
        if data[i + 4:i + 8] in KEEP:
            out.append(data[i:i + 12 + n])
        i += 12 + n
    return b"".join(out)


def main():
    folder = next((f for f in FOLDERS if os.path.isfile(os.path.join(HERE, f, "icon.ico"))), None)
    if not folder:
        print("No icon folder found (looked for: " + ", ".join(FOLDERS) + ")", file=sys.stderr)
        return 1
    lines = ['"""Generated by embed_icons.py: app icons as base64 PNG. Do not edit by hand."""', "ICONS = {"]
    for n in SIZES:
        path = os.path.join(HERE, folder, f"icon-{n}.png")
        if not os.path.isfile(path):
            print("Missing " + path, file=sys.stderr)
            return 1
        with open(path, "rb") as f:
            lines.append(f'    {n}: "{base64.b64encode(strip_png(f.read())).decode()}",')
    lines.append("}")
    with open(os.path.join(HERE, "icon_data.py"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(folder)
    return 0


if __name__ == "__main__":
    sys.exit(main())
